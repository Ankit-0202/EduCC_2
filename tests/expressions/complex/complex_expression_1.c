#include <stdio.h>

int main() {
    int x = 5;
    int y = 10;
    int z = (x << 1) | (y >> 1); // 10 | 5 = 15
    printf("(5 << 1) | (10 >> 1) = %d\n", z);
    
    int w = ~x & y; // (~0...0101) & 0...1010 = ...1010 & 0...1010 = 0...1010 = 10
                    // ~5: ...11111010. 10: ...00001010. AND: ...00001010 -> 10.
    printf("~5 & 10 = %d\n", w);
    
    return 0;
}

